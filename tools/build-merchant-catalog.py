#!/usr/bin/env python3
"""Generate MerchantCatalogData.java from the two reviewed CSVs in tools/fixtures.

    python tools/build-merchant-catalog.py          # rewrite the Java file
    python tools/build-merchant-catalog.py --check  # exit 1 when the Java file is out of date

The CSVs are the source of truth; the Java file is generated and never edited by hand.
"""
import csv, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CATALOG = ROOT / "tools/fixtures/merchant-catalog-2026-11-05.csv"
KEYWORDS = ROOT / "tools/fixtures/merchant-keywords-2026-11-05.csv"
OUT = ROOT / "app/src/main/java/com/mohamedgamal/masareef/MerchantCatalogData.java"
# «رعاية صحية» was merged into «صحة» (schema 29).
RENAMED = {"رعاية صحية": "صحة"}
ALLOWED = {"غير مصنف", "أكل وشرب", "مقاهي", "بقالة", "مواصلات", "فواتير", "اشتراكات", "أقساط", "تسوق", "صحة", "ترفيه", "رياضة", "تعليم"}


def rows(path):
    with open(path, encoding="utf-8-sig", newline="") as handle:
        return list(csv.DictReader(handle))


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def category(value, where):
    value = RENAMED.get(value.strip(), value.strip())
    if value not in ALLOWED:
        raise SystemExit(f"{where}: unknown category {value!r}")
    return value


def render():
    lines = ["package com.mohamedgamal.masareef;", "",
             "/** GENERATED by tools/build-merchant-catalog.py from tools/fixtures/merchant-*-2026-11-05.csv. Do not edit by hand. */",
             "final class MerchantCatalogData {",
             "    /** {name, name_ar, category, alias...} */",
             "    static final String[][] CATALOG = {"]
    seen = set()
    for number, row in enumerate(rows(CATALOG), start=2):
        name = row["name"].strip()
        if not name or name.lower() in seen:
            raise SystemExit(f"catalog line {number}: empty or duplicate name {name!r}")
        seen.add(name.lower())
        aliases = [a.strip() for a in row["sms_aliases"].split("|") if a.strip()]
        if not aliases:
            raise SystemExit(f"catalog line {number}: {name} has no alias")
        fields = [name, row["name_ar"].strip(), category(row["category"], f"catalog line {number}")] + aliases
        lines.append("        {" + ", ".join(literal(f) for f in fields) + "},")
    lines += ["    };", "    /** {category, keyword...}: whole words or phrases inside the merchant name, used only when no catalog entry matched. */",
              "    static final String[][] KEYWORDS = {"]
    for number, row in enumerate(rows(KEYWORDS), start=2):
        words = [w.strip() for w in row["keywords_in_merchant_name"].split("|") if w.strip()]
        fields = [category(row["category"], f"keywords line {number}")] + words
        lines.append("        {" + ", ".join(literal(f) for f in fields) + "},")
    lines += ["    };", "", "    private MerchantCatalogData() {}", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
